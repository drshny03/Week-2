package com.tit.week02.day05.hybridinheritance.restaurant;

class Person {
    private String name;
    private int id;

    // Constructor
    public Person(String name, int id) {
        this.name = name;
        this.id = id;
    }

    // Getters for name and id
    public String getName() {
        return name;
    }

    public int getId() {
        return id;
    }
}
